#!/usr/bin/env python3
"""make_version_h.py - write src/version.h + src/version.hpp for a build that cannot run premake's prebuild step.

    python3 iw4x32/tools/make_version_h.py [--src DIR]

premake5.lua generates these two files in a prebuild step (generate-buildinfo), which needs git inside the build
environment. The Wine/MSVC build (tools-re/build_iw4x_fork.sh) strips prebuild/postbuild commands, so the files
have to exist before msbuild runs - Branding.cpp, Updater.cpp, Console.cpp, ... include version.hpp.
The revision follows the same rule as getRevisionNumber() in premake5.lua: the newest upstream r<number> tag this
fork is based on (r5154), not our own commit count - REVISION_STR is what the game shows, what a server
advertises, and what Updater.cpp compares against the latest IW4x release. Both files are gitignored."""
import argparse, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def git(*args):
    return subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True, text=True).stdout.strip()


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("--src", default=os.path.join(ROOT, "src"))
    a = ap.parse_args()

    tag = git("describe", "--tags", "--abbrev=0", "--match", "r[0-9]*")
    rev = re.fullmatch(r"r(\d+)", tag).group(1) if re.fullmatch(r"r(\d+)", tag) else git("rev-list", "--count", "HEAD")
    branch = git("branch", "--show-current") or "release"   # detached HEAD (a tag checkout): not develop, no EXPERIMENTAL_BUILD

    h = ("/*\n * Automatically generated by iw4x32/tools/make_version_h.py.\n * Do not touch!\n */\n\n"
         f'#define GIT_BRANCH "{branch}"\n\n// Revision definition\n#define REVISION {rev}\n'
         f'#define REVISION_STR "r{rev}"\n')
    if branch == "develop":
        h += "\n// Branch-specific definitions\n#define EXPERIMENTAL_BUILD\n"
    hpp = ("/*\n * Automatically generated by iw4x32/tools/make_version_h.py.\n * Do not touch!\n *\n"
           " * The Resource Compiler ignores C++ headers that are not STDInclude.hpp, so all version info lives\n"
           " * in version.h (premake5.lua generate-buildinfo).\n */\n\n#include \".\\version.h\"\n")
    for name, body in (("version.h", h), ("version.hpp", hpp)):
        p = os.path.join(a.src, name)
        old = open(p).read() if os.path.isfile(p) else ""
        if old != body:
            open(p, "w").write(body)
            print(f"make_version_h: wrote {os.path.relpath(p, ROOT)} (r{rev}, branch {branch})")
        else:
            print(f"make_version_h: {os.path.relpath(p, ROOT)} already current (r{rev})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
